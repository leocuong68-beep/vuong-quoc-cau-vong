// English for the sorting questions: template (Vietnamese) → English with {x}
const ASK_EN = {
  '{x}: là đẩy hay kéo?': '{x}: push or pull?',
  'Nam châm có hút {x} không?': 'Does a magnet pull {x}?',
  '{x} có cho điện chạy qua không?': 'Does electricity go through {x}?',
  '{x}: ban ngày hay ban đêm?': '{x}: day or night?',
  '{x}: nóng hay lạnh?': '{x}: hot or cold?',
  'Thả {x} vào nước: nổi hay chìm?': 'Put {x} in water: does it float or sink?',
};
const cap = (t) => t.charAt(0).toUpperCase() + t.slice(1);
export const enAsk = (template, thing) => {
  const t = ASK_EN[template];
  if (!t) return undefined;
  const x = EN[thing] || thing;
  return t.startsWith('{x}') ? t.replace('{x}', cap(x)) : t.replace('{x}', x);
};
// The text for a language: its own field, else (for English) the dictionary, else Vietnamese.
export const pickText = (text, lang) => {
  if (!text) return '';
  if (typeof text === 'string') return text;
  if (text[lang]) return text[lang];
  if (lang === 'en' && text.vi && EN[text.vi]) return EN[text.vi];
  return text.vi || text.el || '';
};
